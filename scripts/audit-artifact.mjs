import fs from "node:fs"
import path from "node:path"
import { parseSrcsetCandidates } from "./srcset.mjs"

function getAllFiles(dir, allFiles = []) {
  const files = fs.readdirSync(dir)
  for (const file of files) {
    const fullPath = path.join(dir, file)
    if (fs.statSync(fullPath).isDirectory()) {
      getAllFiles(fullPath, allFiles)
    } else {
      allFiles.push(fullPath)
    }
  }
  return allFiles
}

const publicFiles = getAllFiles("public")
console.log("Total public files in public/:", publicFiles.length)

const htmlFiles = publicFiles.filter(
  (f) =>
    f.endsWith(".html") ||
    (!path.basename(f).includes(".") &&
      !f.endsWith(".map") &&
      !f.endsWith(".xml") &&
      !f.endsWith(".svg") &&
      !f.endsWith(".png") &&
      !f.endsWith(".ico")),
)
console.log("HTML and extensionless route files:", htmlFiles.length)

const forbiddenTerms = [
  "\\bM3\\b",
  "\\bM3\\.1\\b",
  "\\bmigration\\b",
  "\\bcheckpoint\\b",
  "\\bscaffold\\b",
  "generated by AI",
  "temporary note",
  "implementation round",
  "\\bprompt\\b",
  "\\bplaceholder\\b",
  "\\bTODO\\b",
]

let termViolations = 0
let h1Violations = 0
let brokenLinks = 0
let brokenSrcs = 0
let checkedHrefs = 0
let checkedSrcs = 0
let checkedSrcsets = 0
let checkedH1Count = 0

// Check for legacy notes
const legacyFiles = ["Static-Routing", "OSPF", "ACL"]
